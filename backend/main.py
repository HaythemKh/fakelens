
from fastapi import FastAPI, UploadFile, File, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from PIL import Image, UnidentifiedImageError
from io import BytesIO

from services.model_loader import load_model
from services.prediction import predict_image


# Initialisation de l'application
app = FastAPI(
    title="FakeLens API",
    description="API for detecting AI-generated images",
    version="1.0.0"
)


# Configuration CORS pour l'extension Chrome
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# Chargement du modèle
try:
    model, device = load_model()
    model_loaded = True
    print("FakeLens model loaded successfully!")
except Exception as e:
    model = None
    device = None
    model_loaded = False
    print(f"Model loading error: {e}")


# Vérification de l'API
@app.get("/")
def root():
    return {
        "service": "FakeLens API",
        "message": "API is running",
        "docs": "/docs"
    }


# Vérification du backend et du modèle
@app.get("/health")
def health():
    return {
        "status": "ok",
        "service": "FakeLens API",
        "model_loaded": model_loaded,
        "device": str(device) if device else None
    }


# Prédiction d'une image
@app.post("/predict")
async def predict(file: UploadFile = File(...)):

    if not model_loaded:
        raise HTTPException(
            status_code=503,
            detail="FakeLens model is not loaded"
        )

    allowed_types = [
        "image/jpeg",
        "image/png",
        "image/webp"
    ]

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Unsupported image format"
        )

    contents = await file.read()

    try:
        image = Image.open(BytesIO(contents)).convert("RGB")
    except (UnidentifiedImageError, OSError):
        raise HTTPException(
            status_code=400,
            detail="Invalid image file"
        )

    try:
        result = predict_image(image)
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Prediction error: {str(e)}"
        )

    response = {
        "filename": file.filename,
        "score": result["score"],
        "probability": result["probability"],
        "predicted_class": result.get("predicted_class"),
        "message": "Prediction generated by FakeLens PyTorch model"
    }
    print(response)
    return response


# Explication de la prédiction (Grad-CAM à intégrer)
@app.post("/explain")
async def explain(file: UploadFile = File(...)):

    allowed_types = [
        "image/jpeg",
        "image/png",
        "image/webp"
    ]

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Unsupported image format"
        )

    contents = await file.read()

    try:
        Image.open(BytesIO(contents)).verify()
    except (UnidentifiedImageError, OSError):
        raise HTTPException(
            status_code=400,
            detail="Invalid image file"
        )

    return {
        "filename": file.filename,
        "explanation": "Grad-CAM is not integrated yet.",
        "heatmap_available": False
    }
