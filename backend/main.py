
from fastapi import FastAPI, UploadFile, File, HTTPException
from PIL import Image, UnidentifiedImageError
from io import BytesIO

from services.model_loader import load_model
from services.prediction import predict_image


# --------------------------------------------------
# APPLICATION
# --------------------------------------------------

app = FastAPI(
    title="FakeLens API",
    description="API for detecting AI-generated images",
    version="1.0.0"
)


# --------------------------------------------------
# LOAD MODEL
# --------------------------------------------------

try:
    model, device = load_model()
    MODEL_LOADED = True
    print(f"FakeLens model loaded successfully on {device}")

except Exception as e:
    model = None
    device = None
    MODEL_LOADED = False
    print(f"Model loading error: {e}")


# --------------------------------------------------
# HOME
# --------------------------------------------------

@app.get("/")
def home():
    return {
        "message": "Welcome to FakeLens API",
        "status": "running"
    }


# --------------------------------------------------
# HEALTH CHECK
# --------------------------------------------------

@app.get("/health")
def health():
    return {
        "status": "ok",
        "service": "FakeLens API",
        "model_loaded": MODEL_LOADED,
        "device": str(device) if device else None
    }


# --------------------------------------------------
# IMAGE VALIDATION
# --------------------------------------------------

def validate_image(file: UploadFile):
    allowed_types = [
        "image/jpeg",
        "image/png",
        "image/webp"
    ]

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Unsupported image format. Use JPG, PNG or WEBP."
        )


# --------------------------------------------------
# PREDICT
# --------------------------------------------------

@app.post("/predict")
async def predict(file: UploadFile = File(...)):

    if not MODEL_LOADED:
        raise HTTPException(
            status_code=503,
            detail="FakeLens model is not loaded."
        )

    validate_image(file)

    try:
        image_bytes = await file.read()
        image = Image.open(BytesIO(image_bytes)).convert("RGB")

        result = predict_image(image)

        return {
    "filename": file.filename,
    "score": result["score"],
    "probability": result["probability"],
    "message": "Prediction generated by FakeLens PyTorch model"
}

    except UnidentifiedImageError:
        raise HTTPException(
            status_code=400,
            detail="Invalid image file."
        )

    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Prediction error: {str(e)}"
        )


# --------------------------------------------------
# EXPLAIN
# --------------------------------------------------

@app.post("/explain")
async def explain(file: UploadFile = File(...)):

    validate_image(file)

    try:
        image_bytes = await file.read()
        Image.open(BytesIO(image_bytes)).verify()

    except Exception:
        raise HTTPException(
            status_code=400,
            detail="Invalid image file."
        )

    return {
        "filename": file.filename,
        "explanation": "Grad-CAM is not integrated yet.",
        "heatmap_available": False
    }
